function enFor(text) {
  if (!text || !/[\u4e00-\u9fff]/.test(text)) return null;
  if (Object.prototype.hasOwnProperty.call(EN_NORM, text)) return EN_NORM[text];
  for (const [re, to] of EN_RULES) {
    const m = text.match(re);
    if (m) return typeof to === 'function' ? to(m) : text.replace(re, to);
  }
  return null;
}
const EN_NORM = {};
for (const k in EN) EN_NORM[k.trim()] = EN[k];

const I18N_ATTRS = ['placeholder', 'aria-label', 'title', 'alt'];
let i18nObserver = null, i18nQueued = false;
const tr = s => LANG === 'en' ? (enFor(s) || s) : s;

function inCode(node) {
  const p = node.parentElement;
  return !!p && (/^(SCRIPT|STYLE|NOSCRIPT)$/.test(p.tagName) || !!p.closest('[contenteditable="true"],[data-no-i18n]'));
}

function translateTextNode(node) {
  if (node.nodeType !== 3 || inCode(node)) return;
  const raw = node.nodeValue;
  if (raw == null) return;
  const m = raw.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const body = m[2];
  if (!body) return;
  const out = enFor(body);
  if (out == null) return;
  node._i18nZh = raw;
  node._i18nEn = m[1] + out + m[3];
  node.nodeValue = node._i18nEn;
}

function translateElement(el) {
  if (el.nodeType !== 1) return;
  if (el.closest && el.closest('[data-no-i18n], .no-i18n')) return;
  let store = el._i18nAttrs;
  for (const attr of I18N_ATTRS) {
    const v = el.getAttribute && el.getAttribute(attr);
    if (!v) continue;
    const out = enFor(v);
    if (out == null) continue;
    store = store || (el._i18nAttrs = {});
    store[attr] = store[attr] || { zh: v, en: out };
    if (attr === 'aria-label' || attr === 'alt') el.setAttribute(attr, out);
    else el.setAttribute(attr, out);
  }
}

function walkI18n(root) {
  if (!root) return;
  if (root.nodeType === 3) { translateTextNode(root); return; }
  if (root.nodeType !== 1 && root.nodeType !== 9 && root.nodeType !== 11) return;
  if (root.nodeType === 1) translateElement(root);
  const tw = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let n = tw.nextNode();
  while (n) {
    if (n.nodeType === 3) translateTextNode(n);
    else translateElement(n);
    n = tw.nextNode();
  }
}

function restoreI18n() {
  const tw = document.createTreeWalker(document.body, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let n = tw.nextNode();
  while (n) {
    if (n.nodeType === 3 && n._i18nZh != null) { n.nodeValue = n._i18nZh; delete n._i18nZh; delete n._i18nEn; }
    else if (n.nodeType === 1 && n._i18nAttrs) {
      for (const attr in n._i18nAttrs) n.setAttribute(attr, n._i18nAttrs[attr].zh);
      delete n._i18nAttrs;
    }
    n = tw.nextNode();
  }
}

function applyLang() {
  const en = LANG === 'en';
  document.documentElement.lang = en ? 'en' : 'zh-CN';
  document.title = en ? 'Photo Corners · instant photo album' : '相角';
  const btn = document.getElementById('langBtn');
  if (btn) { btn.textContent = en ? '中文' : 'English'; btn.setAttribute('aria-label', en ? 'Switch to Chinese' : 'Switch to English'); }
  if (en) walkI18n(document.body); else restoreI18n();
}

function setLang(lang) {
  const next = lang === 'en' ? 'en' : 'zh';
  if (next === LANG) { applyLang(); return; }
  if (next === 'zh') restoreI18n();
  LANG = next;
  try { localStorage.setItem(LANG_KEY, LANG); } catch (e) {}
  applyLang();
  // 画面上的中文（拼页成品、相册页）重画一次，日期分组也按语言显示。
  try {
    if (typeof alb !== 'undefined' && alb && typeof drawAlbum === 'function' && !document.getElementById('albumPanel').hidden) drawAlbum();
    if (typeof ed !== 'undefined' && ed && typeof updateNote === 'function') updateNote();
  } catch (e) {}
}

function startI18n() {
  applyLang();
  if (i18nObserver) return;
  i18nObserver = new MutationObserver(records => {
    if (LANG !== 'en' || i18nQueued) return;
    i18nQueued = true;
    queueMicrotask(() => {
      i18nQueued = false;
      if (LANG !== 'en') return;
      walkI18n(document.getElementById('app') || document.body);
    });
  });
  i18nObserver.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: I18N_ATTRS });
}

